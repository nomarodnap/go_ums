type RegulationItem struct {
	ID           string          `json:"id"`
	Topic        RegulationTopic `json:"topic"`
	TopicName    string          `json:"topicName"`
	Title        string          `json:"title"`
	Reference    string          `json:"reference"`
	Summary      string          `json:"summary"`
	Details      []string        `json:"details"`
	RequiredDocs []string        `json:"requiredDocs"`
	ActionSteps  []string        `json:"actionSteps"`
	Keywords     []string        `json:"keywords"`
}

type KnowledgeService struct {
	items []RegulationItem
}

func NewKnowledgeService() *KnowledgeService {
	return &KnowledgeService{
		items: defaultRegulations(),
	}
}

func (s *KnowledgeService) Search(ctx context.Context, query string, topic string) []RegulationItem {
	if s == nil || len(s.items) == 0 {
		return []RegulationItem{}
	}

	q := strings.ToLower(strings.TrimSpace(query))
	t := strings.ToLower(strings.TrimSpace(topic))

	type scoredItem struct {
		item  RegulationItem
		score int
	}

	var candidates []scoredItem

	for _, item := range s.items {
		// Topic filter
		if t != "" && t != "all" {
			matchTopic := false
			if strings.EqualFold(string(item.Topic), t) {
				matchTopic = true
			} else if strings.Contains(strings.ToLower(item.TopicName), t) {
				matchTopic = true
			} else {
				// Thai topic keyword mapping
				switch {
				case strings.Contains(t, "โทรศัพท์") && item.Topic == TopicPhoneCeilings:
					matchTopic = true
				case (strings.Contains(t, "ผ่อนผัน") || strings.Contains(t, "เอกสาร") || strings.Contains(t, "น้ำรั่ว")) && item.Topic == TopicWaiverAndProof:
					matchTopic = true
				case (strings.Contains(t, "ข้ามปี") || strings.Contains(t, "กันเงิน")) && item.Topic == TopicFiscalRollover:
					matchTopic = true
				case strings.Contains(t, "เบิกจ่าย") && item.Topic == TopicDisbursementRules:
					matchTopic = true
				case (strings.Contains(t, "โอน") || strings.Contains(t, "งบประมาณ")) && item.Topic == TopicBudgetTransfer:
					matchTopic = true
				case (strings.Contains(t, "ผิดปกติ") || strings.Contains(t, "เกณฑ์") || strings.Contains(t, "audit")) && item.Topic == TopicAuditCriteria:
					matchTopic = true
				}
			}
			if !matchTopic {
				continue
			}
		}

		if q == "" {
			candidates = append(candidates, scoredItem{item: item, score: 10})
			continue
		}

		score := 0

		// 1. Match item keywords inside the query (ideal for non-space-delimited Thai)
		for _, kw := range item.Keywords {
			lkw := strings.ToLower(strings.TrimSpace(kw))
			if len([]rune(lkw)) >= 2 && strings.Contains(q, lkw) {
				score += 25
			}
		}

		// 2. Match Title and Summary
		lTitle := strings.ToLower(item.Title)
		lSummary := strings.ToLower(item.Summary)
		if strings.Contains(q, lTitle) || strings.Contains(lTitle, q) {
			score += 35
		}
		if strings.Contains(q, lSummary) || strings.Contains(lSummary, q) {
			score += 20
		}

		// 3. Match whitespace tokens if user included spaces
		qTokens := strings.Fields(q)
		for _, token := range qTokens {
			tok := strings.ToLower(strings.TrimSpace(token))
			if len([]rune(tok)) < 2 {
				continue
			}

			if strings.Contains(lTitle, tok) {
				score += 20
			}
			if strings.Contains(lSummary, tok) {
				score += 15
			}
			for _, det := range item.Details {
				if strings.Contains(strings.ToLower(det), tok) {
					score += 10
				}
			}
			for _, doc := range item.RequiredDocs {
				if strings.Contains(strings.ToLower(doc), tok) {
					score += 10
				}
			}
		}

		if score > 0 {
			candidates = append(candidates, scoredItem{item: item, score: score})
		}
	}

	// Sort by score descending
	for i := 0; i < len(candidates)-1; i++ {
		for j := i + 1; j < len(candidates); j++ {
			if candidates[j].score > candidates[i].score {
				candidates[i], candidates[j] = candidates[j], candidates[i]
			}
		}
	}

	limit := 4
	if len(candidates) < limit {
		limit = len(candidates)
	}

	res := make([]RegulationItem, 0, limit)
	for i := 0; i < limit; i++ {
		res = append(res, candidates[i].item)
	}
	return res
}

